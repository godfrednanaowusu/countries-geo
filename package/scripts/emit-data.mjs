// Turns the canonical JSON dataset (src/data) into JS modules under src/generated, which
// tsc then compiles into both the ESM and CommonJS builds.
//
// - Every data file becomes `export default JSON.parse('...')` (fast to parse, tiny overhead).
// - loaders.js maps each country / language to a *static* `import()` so every bundler
//   (webpack, Vite/Rollup, esbuild, Next.js) can split them into lazily loaded chunks.
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src', 'data');
const out = join(root, 'src', 'generated');

rmSync(out, { recursive: true, force: true });

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
  });

for (const file of walk(src)) {
  const rel = relative(src, file).replace(/\.json$/, '.js');
  const json = JSON.stringify(JSON.parse(readFileSync(file, 'utf8')));
  const literal = json.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  const target = join(out, rel);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `export default JSON.parse('${literal}');\n`);
}

const index = JSON.parse(readFileSync(join(src, 'index.json'), 'utf8'));
const lines = [
  '// Generated by scripts/emit-data.mjs. Do not edit.',
  'export const cities = {',
  ...index.cities.map((cc) => `  ${cc}: () => import('./cities/${cc}.js'),`),
  '};',
  'export const languages = {',
  ...index.languages.filter((l) => l !== 'en').map((l) => `  ${l}: () => import('./i18n/${l}/core.js'),`),
  '};',
  '// Per-language index of city translation chunks, so the table itself is only loaded on use.',
  'export const cityTranslations = {',
  ...Object.keys(index.cityTranslations).map((l) => `  ${l}: () => import('./i18n/${l}/cities/index.js'),`),
  '};',
  '',
];
writeFileSync(join(out, 'loaders.js'), lines.join('\n'));
for (const [lang, ccs] of Object.entries(index.cityTranslations)) {
  const body = ccs.map((cc) => `  ${cc}: () => import('./${cc}.js'),`).join('\n');
  writeFileSync(join(out, 'i18n', lang, 'cities', 'index.js'), `export default {\n${body}\n};\n`);
}
console.log(`emitted data modules into ${relative(root, out)}`);
